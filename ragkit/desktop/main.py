# Paths that do NOT require the backend token (health check used by watchdog)
_PUBLIC_PATHS = {"/health"}


class BackendTokenMiddleware(BaseHTTPMiddleware):
    """Reject requests that do not carry a valid X-Backend-Token header.

    The token is a UUID v4 generated by the Tauri shell at startup and passed
    to the Python backend via ``--secret``.  This prevents any other local
    process from calling the API.
    """

    def __init__(self, app: FastAPI, *, secret: str) -> None:
        super().__init__(app)
        self._secret = secret

    async def dispatch(self, request: Request, call_next):  # type: ignore[override]
        if request.url.path in _PUBLIC_PATHS:
            return await call_next(request)

        token = request.headers.get("X-Backend-Token", "")
        if not hmac.compare_digest(token, self._secret):
            return JSONResponse(status_code=401, content={"detail": "Unauthorized"})

        return await call_next(request)


# ---------------------------------------------------------------------------
# Security headers middleware
# ---------------------------------------------------------------------------

class SecurityHeadersMiddleware(BaseHTTPMiddleware):
    async def dispatch(self, request: Request, call_next):  # type: ignore[override]
        response = await call_next(request)
        response.headers["X-Content-Type-Options"] = "nosniff"
        response.headers["X-Frame-Options"] = "DENY"
        response.headers["Cache-Control"] = "no-store"
        response.headers["X-Request-Id"] = str(uuid.uuid4())
        return response


