def create_app(*, backend_secret: str = "") -> FastAPI:
    app = FastAPI(title="RAGKIT Desktop API", version=VERSION)

    # --- Security middlewares (outermost first) ---
    if backend_secret:
        app.add_middleware(BackendTokenMiddleware, secret=backend_secret)

    app.add_middleware(SecurityHeadersMiddleware)

    app.add_middleware(
        CORSMiddleware,
        allow_origins=["http://localhost:1420", "https://tauri.localhost", "http://tauri.localhost"],
        allow_credentials=True,
        allow_methods=["GET", "POST", "PUT", "DELETE", "OPTIONS"],
        allow_headers=["Content-Type", "X-Backend-Token"],
    )

    from ragkit.desktop.api import wizard, ingestion, sources, chunking, embedding, vector_store, retrieval, rerank, llm, chat, agents, monitoring, security, general
    from ragkit.desktop.ingestion_runtime import runtime

    app.include_router(wizard.router)
    app.include_router(sources.router)
    app.include_router(ingestion.router)
    app.include_router(ingestion.settings_router)
    app.include_router(chunking.router)
    app.include_router(embedding.router)
    app.include_router(vector_store.router)
    app.include_router(retrieval.router)
    app.include_router(rerank.router)
    app.include_router(llm.router)
    app.include_router(agents.router)
    app.include_router(chat.router)
    app.include_router(monitoring.router)
    app.include_router(security.router)
    app.include_router(general.router)

    @app.on_event("startup")
    async def _start_background_tasks():
        _install_windows_error_handler()
        # Initialize conversations DB and migrate existing JSON files
        from ragkit.desktop.conversation_db import get_conversation_db
        db = get_conversation_db()
        db.migrate_json_files()
        runtime.ensure_background_tasks()
        from ragkit.desktop.sync_scheduler import sync_scheduler
        await sync_scheduler.start()

    @app.on_event("shutdown")
    async def _stop_background_tasks():
        from ragkit.desktop.sync_scheduler import sync_scheduler
        await sync_scheduler.stop()

    @app.get("/health")
    async def health_check():
        return {"ok": True, "version": VERSION}

    @app.post("/shutdown")
    async def shutdown():
        logger.info("Shutdown requested")
        asyncio.get_event_loop().call_later(0.5, lambda: sys.exit(0))
        return {"ok": True}

    return app


def _install_windows_error_handler() -> None:
    """Suppress ConnectionResetError on Windows ProactorEventLoop.

    Windows raises WinError 10054 when a client disconnects abruptly (e.g.
    Tauri health-check probes).  Without this handler the unhandled exception
    crashes the entire uvicorn server.
    """
    if sys.platform != "win32":
        return

    try:
        loop = asyncio.get_running_loop()
    except RuntimeError:
        loop = asyncio.get_event_loop()
    original_handler = loop.get_exception_handler()

    def _handler(loop: asyncio.AbstractEventLoop, context: dict) -> None:
        exception = context.get("exception")
        if isinstance(exception, ConnectionResetError):
            logger.debug("Suppressed ConnectionResetError: %s", exception)
            return
        if original_handler:
            original_handler(loop, context)
        else:
            loop.default_exception_handler(context)

    loop.set_exception_handler(_handler)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--port", type=int, default=8100)
    parser.add_argument("--secret", type=str, default="")
    args = parser.parse_args()

    setup_logging()

    if not args.secret:
        logger.warning("No --secret provided; backend token authentication is DISABLED")

    app = create_app(backend_secret=args.secret)
    logger.info(f"Starting RAGKIT backend on port {args.port}")
    uvicorn.run(
        app,
        host="127.0.0.1",
        port=args.port,
        log_level="info",
        timeout_keep_alive=30,
    )


if __name__ == "__main__":
    main()
